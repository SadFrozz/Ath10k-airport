#!/usr/bin/env python3
"""Synthetic PMF CCMP-128 fixtures; independent cryptography AESCCM provider.

IEEE 802.11 management nonce = 0x10 || A2 || PN (big endian); AAD is the
masked 24-byte header without Duration and with the sequence number zeroed.
No production password/key, project crypto code, device or network access.
"""
from cryptography.hazmat.primitives.ciphers.aead import AESCCM
from cryptography.hazmat.primitives.cmac import CMAC
from cryptography.hazmat.primitives.ciphers import algorithms

KEY = bytes(range(16))
STA = bytes.fromhex('020102030405')
AP = bytes.fromhex('02060708090a')

def header(subtype=0xd0, incoming=True):
    return bytes([subtype, 0x40, 0x21, 0x43]) + (STA + AP if incoming else AP + STA) + AP + bytes.fromhex('3012')

def vector(name, h, body, pn):
    mask = (int.from_bytes(h[:2], 'little') & ~0x3800).to_bytes(2, 'little')
    aad = mask + h[4:22] + bytes([h[22] & 15, 0])
    nonce = b'\x10' + h[10:16] + pn.to_bytes(6, 'big')
    le = pn.to_bytes(6, 'little')
    ccmp = le[:2] + b'\0\x20' + le[2:]
    cipher = AESCCM(KEY, tag_length=8).encrypt(nonce, body, aad)
    assert AESCCM(KEY, tag_length=8).decrypt(nonce, cipher, aad) == body
    emit(name+'_plain', h+body)
    emit(name+'_wire', h+ccmp+cipher)
    emit(name+'_decrypted', h+ccmp+body+cipher[-8:])
    if name.startswith('c_tx'):
        emit(name+'_hardware', h+ccmp+body+bytes(8))
    print(f'static constexpr uint64_t {name}_pn=0x{pn:012x}ull;')

def emit(name, data):
    print(f'static constexpr uint8_t {name}[]={{'+','.join(f'0x{x:02x}' for x in data)+'};')

print('// Generated by tools/sae/generate-pmf-ccmp-vectors.py; synthetic AESCCM fixtures.')
emit('c_key', KEY);emit('c_sta', STA);emit('c_ap', AP)
vector('c_query', header(), bytes.fromhex('08011234'), 0x010203040506)
vector('c_deauth', header(0xc0), bytes.fromhex('0600'), 1)
vector('c_disassoc', header(0xa0), bytes.fromhex('0700'), 0xffffffffffff)
for size in [15, 16, 17, 472]:
    body = bytes([10, 1]) + bytes((i*37+19)%256 for i in range(size-2))
    vector(f'c_body{size}', header(), body, 0x12340000 + size)
vector('c_tx', header(incoming=False), bytes.fromhex('08001234'), 0x010203040507)
vector('c_public', header(), bytes.fromhex('04011234'), 12)
vector('c_vendor', header(), bytes.fromhex('7e01020304'), 13)

# Group deauthentication uses independent BIP-CMAC, not CCMP/firmware key slots.
bip = bytes.fromhex('c0000000') + b'\xff'*6 + AP + AP + bytes(2) + bytes.fromhex('06004c100400070000000000') + bytes(8)
aad = bip[:2] + bip[4:22] + bip[24:]
mac = CMAC(algorithms.AES(KEY));mac.update(aad)
bip = bip[:-8] + mac.finalize()[:8]
emit('c_bip_disconnect', bip)

def group_vector(name, body, pn, subtype=0xd0, flags=0, key=KEY, key_id=4):
    h = bytes([subtype, flags, 0, 0]) + b'\xff'*6 + AP + AP + bytes(2)
    frame = h + body + bytes.fromhex('4c10') + key_id.to_bytes(2, 'little') + pn.to_bytes(6, 'little') + bytes(8)
    fc = (int.from_bytes(h[:2], 'little') & ~0x3800).to_bytes(2, 'little')
    mac = CMAC(algorithms.AES(key));mac.update(fc + frame[4:22] + frame[24:])
    frame = frame[:-8] + mac.finalize()[:8]
    emit(name+'_wire', frame);emit(name+'_plain', h+body)
    print(f'static constexpr uint64_t {name}_pn=0x{pn:012x}ull;')

group_vector('c_group_action', bytes.fromhex('00042503012c01'), 8)
group_vector('c_group_disassoc', bytes.fromhex('0700'), 9, subtype=0xa0)
group_vector('c_group_max', bytes.fromhex('00042503012c01'), 0xffffffffffff)
group_vector('c_group_zero', bytes.fromhex('00042503012c01'), 0)
group_vector('c_group_protected', bytes.fromhex('00042503012c01'), 10, flags=0x40)
for category in [4, 7, 11, 15, 20, 21, 22, 127]:
    group_vector(f'c_group_nonrobust_{category}', bytes([category, 0, 1]), 10)
for pn in [1, 2, 3]:
    vector(f'c_txpn{pn}', header(incoming=False), bytes.fromhex('08001234'), pn)

vector('c_query_request', header(), bytes.fromhex('08001234'), 2)
vector('c_tx_response', header(incoming=False), bytes.fromhex('08011234'), 1)

vector('c_tpc_request', header(), bytes.fromhex('00025a2200'), 3)
vector('c_measure_request', header(), bytes.fromhex('00006b2603770003'), 4)
vector('c_tx_tpc', header(incoming=False), bytes.fromhex('00035a23020a00'), 1)
vector('c_tx_measure', header(incoming=False), bytes.fromhex('00016b2703770203'), 1)

# Independent BIP key-rotation/in-flight fixtures, with synthetic public keys.
rotated = bytes([KEY[0] ^ 1]) + KEY[1:]
