from cryptography.hazmat.primitives.ciphers.aead import AESCCM

KEY = bytes(range(16))
STA = bytes.fromhex('020102030405')
AP = bytes.fromhex('02060708090a')

def header(subtype=0xd0, incoming=True):
    return bytes([subtype, 0x40, 0x21, 0x43]) + (STA + AP if incoming else AP + STA) + AP + bytes.fromhex('3012')

def vector(name, h, body, pn):
    mask = (int.from_bytes(h[:2], 'little') & ~0x3800).to_bytes(2, 'little')
    aad = mask + h[4:22] + bytes([h[22] & 15, 0])
    nonce = b'\x10' + h[10:16] + pn.to_bytes(6, 'big')
    le = pn.to_bytes(6, 'little')
    ccmp = le[:2] + b'\0\x20' + le[2:]
    cipher = AESCCM(KEY, tag_length=8).encrypt(nonce, body, aad)
    assert AESCCM(KEY, tag_length=8).decrypt(nonce, cipher, aad) == body
    emit(name+'_plain', h+body)
    emit(name+'_wire', h+ccmp+cipher)
    emit(name+'_decrypted', h+ccmp+body+cipher[-8:])
    print(f'static constexpr uint64_t {name}_pn=0x{pn:012x}ull;')

def emit(name, data):
    print(f'static constexpr uint8_t {name}[]={{'+','.join(f'0x{x:02x}' for x in data)+'};')

