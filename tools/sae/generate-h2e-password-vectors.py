#!/usr/bin/env python3
"""Independent integer/HMAC SAE group-19 H2E credential boundary vectors.
All inputs are synthetic. No CoreCrypto or production driver code is used.
cryptography validates every resulting point against SECP256R1.
"""
from pathlib import Path
import hmac
from cryptography.hazmat.primitives.asymmetric import ec

P = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff
N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551
A = P - 3
B = 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b
Z = P - 10

def inv(x):
    return pow(x, -1, P)

def add(u, v):
    if u is None:
        return v
    if v is None:
        return u
    x, y = u
    xx, yy = v
    if x == xx and (y + yy) % P == 0:
        return None
    slope = ((3*x*x+A)*inv(2*y) if u == v else (yy-y)*inv(xx-x)) % P
    rx = (slope*slope-x-xx) % P
    return rx, (slope*(x-rx)-y) % P

def mul(k, q):
    result = None
    while k:
        if k & 1:
            result = add(result, q)
        q = add(q, q)
        k >>= 1
    return result

def encode(q):
    ec.EllipticCurvePublicNumbers(*q, ec.SECP256R1()).public_key()
    return b''.join(v.to_bytes(32, 'big') for v in q)

def sswu(u):
    t = (Z*u*u) % P
    denominator = (t*t+t) % P
    x1 = (-B*inv(A)*(1+inv(denominator))) % P if denominator else (B*inv(Z*A)) % P
    for x in (x1, t*x1 % P):
        gx = (x*x*x+A*x+B) % P
        y = pow(gx, (P+1)//4, P)
        if y*y % P == gx:
            if y % 2 != u % 2:
                y = (-y) % P
            return x, y
    raise AssertionError('SSWU produced no square')

def derive(ssid, password, identifier):
    seed = hmac.digest(ssid, password+identifier, 'sha256')
    points = []
    for label in (b'SAE Hash to Element u1 P1', b'SAE Hash to Element u2 P2'):
        first = hmac.digest(seed, label+b'\x01', 'sha256')
        expanded = first+hmac.digest(seed, first+label+b'\x02', 'sha256')[:16]
        points.append(sswu(int.from_bytes(expanded, 'big') % P))
    pt = add(*points)
    addresses = bytes([2, 6, 7, 8, 9, 10, 2, 1, 2, 3, 4, 5])
    scalar = int.from_bytes(hmac.digest(bytes(32), addresses, 'sha256'), 'big') % (N-1) + 1
    pwe = mul(scalar, pt)
    # The session test's deterministic random=7, mask=3: scalar=10, element=-3*PWE.
    commit = (10).to_bytes(32, 'big') + encode(mul(N-3, pwe))
    return encode(pt), encode(pwe), commit

known = derive(b'test-ssid', b'test-password', b'test-id')
assert known[0].hex() == '84347bb62237b0df47cae8e044af1c097d15f635dbed2ae56b6b1740189a73f5de793758cf3db5c47ef4e2636e730ab88551c914ebdb8e9ef4e3303b7c9d5c1b'
assert known[1].hex() == '8e3a78633b49752947fa2ec5fe4f9ceb7d80763eb62ecbaa468a8b570618f660a4932a75da3118352dfa78c45ed3c039d020c8e1b9f32504a8e725e085b6930d'
cases = [(b'\x00', b'\x00', b''),
         (bytes(range(32)), bytes((37*i) % 256 for i in range(64)), bytes(range(254))),
         ('Сеть'.encode(), 'пароль'.encode(), b'')]
lines = ['// Generated by tools/sae/generate-h2e-password-vectors.py; synthetic credentials only.',
         'namespace H2EPasswordVectors {',
         'struct Vector { const char *ssid,*password,*identifier,*pt,*pwe,*commit; };',
         'static constexpr Vector vectors[]={']
for case in cases:
    values = (*case, *derive(*case))
    lines.append('  {' + ','.join('"'+v.hex()+'"' for v in values) + '},')
lines += ['};', '}']
output = Path(__file__).resolve().parents[2]/'tests/h2e_password_vectors.inc'
output.write_text('\n'.join(lines)+'\n')
print('Generated 3 independent H2E credential vectors')
