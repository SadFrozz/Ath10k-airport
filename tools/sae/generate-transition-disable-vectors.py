#!/usr/bin/env python3
"""Public synthetic EAPOL fixtures using independent AES-KW and CMAC.

Reads only the checked-in synthetic fixtures; writes C++ arrays to stdout.
"""
from pathlib import Path
import re
from cryptography.hazmat.primitives import cmac
from cryptography.hazmat.primitives.ciphers import algorithms
from cryptography.hazmat.primitives.keywrap import aes_key_wrap, aes_key_unwrap
ROOT = Path(__file__).resolve().parents[2]
def load(name):
    text = (ROOT / 'tests' / name).read_text()
    return {n: bytes(int(x) for x in values.split(',') if x.strip())
            for n, values in re.findall(r'uint8_t (\w+)\[\]=\{([^}]+)\}', text)}
w = load('sae_eapol_vectors.inc')
s = load('sha256_vectors.inc')
def elements(packet, ptk):
    plain = aes_key_unwrap(ptk[16:32], packet[113:])
    at = 0
    while at < len(plain):
        if plain[at] == 221 and (at + 1 == len(plain) or plain[at+1] == 0):
            assert not any(plain[at+1:])
            break
        end = at + 2 + plain[at+1]
        assert end <= len(plain)
        at = end
    return plain[:at]
def kde(bitmap):
    return bytes([221, 4 + len(bitmap), 0x50, 0x6f, 0x9a, 0x20]) + bitmap
def packet(base, ptk, extra=b'', change_rsn=False, bad_wrap=False, replay=None):
    plain = bytearray(elements(base, ptk))
    if change_rsn: plain[19] ^= 1
    plain += extra
    if len(plain) % 8:
        plain += bytes([221]) + bytes((-len(plain)-1) % 8)
    encrypted = bytearray(aes_key_wrap(ptk[16:32], bytes(plain)))
    if bad_wrap: encrypted[-1] ^= 1
    frame = bytearray(base[:113]) + encrypted
    frame[16:18] = (len(frame)-18).to_bytes(2, 'big')
    frame[111:113] = len(encrypted).to_bytes(2, 'big')
    if replay is not None: frame[23:31] = replay.to_bytes(8, 'big')
    frame[95:111] = bytes(16)
    mic = cmac.CMAC(algorithms.AES(ptk[:16])); mic.update(bytes(frame[14:]))
    frame[95:111] = mic.finalize()
    return bytes(frame)
fixtures = {
    'td_m3': packet(w['w_m3'], w['w_ptk'], kde(b'\x01')),
    'td_retry': packet(w['w_m3'], w['w_ptk'], kde(b'\x01'), replay=3),
    'td_long': packet(w['w_m3'], w['w_ptk'], kde(bytes([0x81]) + bytes(249) + b'\x40')),
    'td_empty': packet(w['w_m3'], w['w_ptk'], kde(b'')),
    'td_duplicate': packet(w['w_m3'], w['w_ptk'], kde(b'\x01') + kde(b'\x08')),
    'td_wrong_rsn': packet(w['w_m3'], w['w_ptk'], kde(b'\x01'), change_rsn=True),
    'td_bad_wrap': packet(w['w_m3'], w['w_ptk'], kde(b'\x01'), bad_wrap=True),
    'td_group': packet(w['w_group_both'], w['w_ptk'], kde(b'\x08')),
    'td_rekey': packet(w['w_rekey3'], w['w_next_ptk'], kde(b'\x08')),
    'td_psk': packet(s['s_m3'], s['s_ptk'], kde(b'\x01')),
}
print('// Generated by tools/sae/generate-transition-disable-vectors.py; public synthetic data.')
for name, value in fixtures.items():
    print('static const uint8_t '+name+'[]={'+','.join(map(str,value))+'};')
