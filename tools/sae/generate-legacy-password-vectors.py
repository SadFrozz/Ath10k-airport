#!/usr/bin/env python3
"""Independent public group-19 hunting-and-pecking vectors; no driver imports."""
from pathlib import Path
import contextlib
import io
import runpy
import hmac

with contextlib.redirect_stdout(io.StringIO()):
    reference = runpy.run_path(str(Path(__file__).with_name('generate-h2e-password-vectors.py')))
P, N, A, B = (reference[k] for k in ['P', 'N', 'A', 'B'])
encode, mul = reference['encode'], reference['mul']
addresses = bytes([2, 6, 7, 8, 9, 10, 2, 1, 2, 3, 4, 5])
prime = P.to_bytes(32, 'big')
lines = ['// Generated by tools/sae/generate-legacy-password-vectors.py; synthetic credentials only.',
         'namespace LegacyPasswordVectors {',
         'struct Vector { const char *password,*pwe,*commit; unsigned counter; };',
         'static constexpr Vector vectors[]={']
for password in (b'\x00', b'test-password', bytes((37*i) % 256 for i in range(64))):
    for counter in range(1, 201):
        seed = hmac.digest(addresses, password+bytes([counter]), 'sha256')
        candidate = hmac.digest(seed, b'\x01\x00SAE Hunting and Pecking'+prime+b'\x00\x01', 'sha256')
        x = int.from_bytes(candidate, 'big')
        if x >= P:
            continue
        gx = (x*x*x+A*x+B) % P
        y = pow(gx, (P+1)//4, P)
        if y*y % P != gx:
            continue
        if y % 2 != seed[-1] % 2:
            y = (-y) % P
        pwe = (x, y)
        commit = (10).to_bytes(32, 'big')+encode(mul(N-3, pwe))
        lines.append('  {'+','.join('"'+v.hex()+'"' for v in [password,encode(pwe),commit])+','+str(counter)+'},')
        break
    else:
        raise AssertionError('no PWE within protocol counter bound')
lines += ['};', '}']
(Path(__file__).resolve().parents[2]/'tests/legacy_password_vectors.inc').write_text('\n'.join(lines)+'\n')
print('Generated 3 independent legacy SAE password vectors')
