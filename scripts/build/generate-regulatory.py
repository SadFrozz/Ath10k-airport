#!/usr/bin/env python3
"""Generate bounded STA 2.4/5GHz rules from pinned wireless-regdb and ath maps."""
from pathlib import Path
import re, math, hashlib
root=Path(__file__).resolve().parents[2];base=root/'regulatory'
symbols={'CTRY_DEBUG':511,'CTRY_DEFAULT':0,'DEBUG_REG_DMN':0xff,'NO_CTL':0xff,'CTL_FCC':0x10,'CTL_MKK':0x40,'CTL_ETSI':0x30}
for n in ['regd.h','regd_common.h']:
 text=(base/n).read_text()
 for key,value in re.findall(r'\b(\w+)\s*=\s*(0x[0-9a-fA-F]+|[0-9]+)\s*(?:,|\n)',text):symbols[key]=int(value,0)
common=(base/'regd_common.h').read_text()
pairs=[]
for a,b,c in re.findall(r'\{\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\}',common.split('static struct reg_dmn_pair_mapping regDomainPairs[] = {')[1].split('};')[0]):pairs.append((symbols[a],symbols[c],symbols[b]))
ath=[]
for a,b,c in re.findall(r'\{\s*(\w+)\s*,\s*(\w+)\s*,\s*"([A-Z0-9]{2})"\s*\}',common.split('static struct country_code_to_enum_rd allCountries[] = {')[1].split('};')[0]):
 if c!='DB':ath.append((symbols[a],symbols[b],c))
flags={'DFS':1,'NO-IR':2,'NO-OUTDOOR':4,'NO-INDOOR':8,'NO-OFDM':16,'PTP-ONLY':32,'PTMP-ONLY':32}
rules=[];countries=[];current=None
for raw in (base/'db.txt').read_text().splitlines():
 line=raw.split('#')[0].strip()
 m=re.match(r'country ([A-Z0-9]{2}):(?:\s*(DFS-\w+))?',line)
 if m:
  if current:countries.append(current)
  current=[m[1],len(rules),0,{'DFS-FCC':1,'DFS-ETSI':2,'DFS-JP':3}.get(m[2],0)];continue
 if not current or not line.startswith('('):continue
 m=re.match(r'\(([\d.]+)\s*-\s*([\d.]+)\s*@\s*([\d.]+)\),\s*\(([^)]+)\)(.*)',line)
 if not m:raise ValueError(line)
 lo,hi,bw=map(float,m.group(1,2,3))
 if hi<2300 or lo>=5925:continue
 power=m[4].strip();tail=m[5];value=float(re.match(r"[0-9.]+",power)[0])
 if 'mW' in power:value=10*math.log10(value)
 half=max(0,min(63,int(math.floor(value*2+1e-8))))
 f=0
 for name,bit in flags.items():
  if re.search(r'\b'+re.escape(name)+r'\b',tail):f|=bit
 # Do not enable country-specific special modes or non-OFDM allocations.
 rules.append((int(lo*1000),int(hi*1000),int(bw),half,f));current[2]+=1
if current:countries.append(current)
countries=[c for c in countries if c[2]]
out='''// Generated by scripts/build/generate-regulatory.py. Do not edit by hand.
// wireless-regdb master-2026-09-03 (ISC); ath regd mappings Linux v6.12 (ISC).
// Source files and licenses are included under regulatory/.
#pragma once
#include <IOKit/IOTypes.h>
namespace Ath10k {
struct RegulatoryRule { UInt32 lowKHz,highKHz;UInt16 maxWidth;UInt8 halfDbm,flags; };
struct RegulatoryCountry { char alpha2[3];UInt16 first,count;UInt8 dfsRegion; };
struct RegulatoryPair { UInt16 rd,ctl2g,ctl5g; };
struct RegulatoryAthCountry { UInt16 code,rd;char alpha2[3]; };
'''
out+='static constexpr RegulatoryRule kRegulatoryRules[]={\n'+''.join('{%d,%d,%d,%d,%d},\n'%x for x in rules)+'};\n'
out+='static constexpr RegulatoryCountry kRegulatoryCountries[]={\n'+''.join('{"%s",%d,%d,%d},\n'%tuple(x) for x in countries)+'};\n'
out+='static constexpr RegulatoryPair kRegulatoryPairs[]={\n'+''.join('{%d,%d,%d},\n'%x for x in pairs)+'};\n'
out+='static constexpr RegulatoryAthCountry kRegulatoryAthCountries[]={\n'+''.join('{%d,%d,"%s"},\n'%x for x in ath)+'};\n}\n'
(root/'src/core/Ath10kRegulatoryData.hpp').write_text(out)
print(f'{len(countries)} countries, {len(rules)} rules, {len(pairs)} ath domain pairs')
(base/'SOURCE.md').write_text('# Sources\n\nwireless-regdb master-2026-09-03, https://kernel.googlesource.com/pub/scm/linux/kernel/git/wens/wireless-regdb/+/refs/tags/master-2026-09-03/\n\nLinux v6.12 ath regd.h/regd_common.h, https://github.com/torvalds/linux/tree/v6.12/drivers/net/wireless/ath\n\n'+''.join(f'{n}: SHA256 {hashlib.sha256((base/n).read_bytes()).hexdigest()}\n\n' for n in ['db.txt','LICENSE','regd.h','regd_common.h']))
